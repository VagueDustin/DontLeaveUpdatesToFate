/**
 * check-brand.mjs: the CI guardrail from @vaguedustin/brand docs/CONSUMING.md.
 *
 * "The single highest-leverage check": fail if a hex literal appears in product source. A colour typed
 * inline is a colour that will not follow the palette when it is retuned upstream, and it is the way
 * every design system quietly rots.
 *
 * Two files are allowed to hold raw values, and both say so in their own header:
 *   src/shared/brand-tokens.ts   the handful the main process needs before any CSS exists
 *   resources/icon-small.svg     a rasterised icon cannot resolve a CSS variable
 *
 * The vendored `styles/brand/*.css` is generated by the brand package and is skipped entirely.
 */

import { readdir, readFile } from 'node:fs/promises';
import { join, relative, resolve, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const SEARCH_ROOTS = ['src', 'resources'];
const EXTENSIONS = new Set(['.ts', '.tsx', '.css', '.html', '.svg']);

/** Paths (relative, POSIX-style) that are permitted to contain raw colour values. */
const ALLOWED = [
  'src/shared/brand-tokens.ts',
  'resources/icon-small.svg',
];

/** Generated or vendored, not product source. */
const SKIPPED_DIRS = ['src/renderer/src/styles/brand'];

const HEX = /#(?:[0-9a-fA-F]{3,4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})\b/g;

/**
 * Colour functions that take literal channel values.
 *
 * `color-mix(in srgb, var(--x) 40%, transparent)` is fine and used everywhere; a bare
 * `rgba(212,175,55,0.4)` is not, because it hard-codes a house colour.
 */
const RAW_FN = /\b(?:rgb|rgba|hsl|hsla)\(\s*[\d.]/g;

async function* walk(dir) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name === 'dist' || entry.name === 'out') continue;
      yield* walk(full);
    } else {
      yield full;
    }
  }
}

const toPosix = (path) => path.split(sep).join('/');

async function main() {
  const problems = [];
  let checked = 0;

  for (const root of SEARCH_ROOTS) {
    for await (const file of walk(join(ROOT, root))) {
      const rel = toPosix(relative(ROOT, file));
      if (!EXTENSIONS.has(file.slice(file.lastIndexOf('.')))) continue;
      if (ALLOWED.includes(rel)) continue;
      if (SKIPPED_DIRS.some((dir) => rel.startsWith(`${dir}/`))) continue;

      checked++;
      const text = await readFile(file, 'utf8');
      const lines = text.split('\n');

      lines.forEach((line, index) => {
        // A hex inside a comment is documentation, not a style declaration.
        const code = line.replace(/\/\/.*$/, '').replace(/\/\*.*?\*\//g, '');

        for (const match of code.matchAll(HEX)) {
          problems.push({ rel, line: index + 1, found: match[0], text: line.trim() });
        }
        for (const match of code.matchAll(RAW_FN)) {
          problems.push({ rel, line: index + 1, found: `${match[0]}…`, text: line.trim() });
        }
      });
    }
  }

  const motion = await motionProblems();
  if (motion.length > 0) {
    console.error(`\nAnimations of layout or paint-heavy properties found in ${motion.length} place(s):\n`);
    for (const m of motion) console.error(`  ${m.rel}:${m.line}  ${m.found}\n    ${m.text.slice(0, 110)}`);
    console.error('\nAnimate transform and opacity only (fate-brand MOTION.md). Use scaleX for fills, a');
    console.error('pseudo-element opacity for glows, and a cross-fade for colour changes.\n');
    process.exitCode = 1;
  } else {
    console.log('motion check passed, only compositor-friendly properties are animated.');
  }

  if (problems.length > 0) {
    console.error(`\nRaw colour values found in ${problems.length} place(s):\n`);
    for (const problem of problems) {
      console.error(`  ${problem.rel}:${problem.line}  ${problem.found}`);
      console.error(`    ${problem.text.slice(0, 110)}`);
    }
    console.error(
      '\nUse a semantic token from the vendored brand CSS instead, e.g. var(--accent-default),',
    );
    console.error('or color-mix(in srgb, var(--status-warning) 30%, transparent).\n');
    process.exitCode = 1;
    return;
  }

  console.log(`brand check passed, no raw colour values in ${checked} product source file(s).`);
}

/**
 * Properties that must not be animated: they re-run layout (width, height) or repaint large areas
 * every frame (box-shadow, filter). Colour changes on `ease` are house style (MOTION.md: "colors
 * change on ease"), so a colour transition is fine; a colour inside a looping @keyframes is not, since
 * it repaints every frame for as long as it runs.
 */
const HEAVY = /^(?:width|height|box-shadow|filter)$/;
const HEAVY_IN_KEYFRAMES = /^(?:width|height|box-shadow|filter|color)$/;

async function motionProblems() {
  const found = [];
  const stylesRoot = join(ROOT, 'src', 'renderer', 'src', 'styles');
  for await (const file of walk(stylesRoot)) {
    const rel = toPosix(relative(ROOT, file));
    if (!rel.endsWith('.css') || SKIPPED_DIRS.some((dir) => rel.startsWith(`${dir}/`))) continue;
    const text = (await readFile(file, 'utf8')).replace(/\/\*[\s\S]*?\*\//g, (c) => c.replace(/[^\n]/g, ' '));
    const lines = text.split('\n');

    // transition / transition-property lists
    lines.forEach((line, index) => {
      const m = /^\s*transition(?:-property)?\s*:\s*([^;]*)/.exec(line);
      if (!m) return;
      // A transition list can continue over following lines until the semicolon.
      let value = m[1];
      for (let j = index + 1; !line.includes(';') && !value.includes(';') && j < lines.length; j++) {
        value += ' ' + lines[j];
        if (lines[j].includes(';')) break;
      }
      for (const part of value.split(',')) {
        const prop = part.trim().split(/\s+/)[0];
        if (prop && HEAVY.test(prop)) found.push({ rel, line: index + 1, found: `transition: ${prop}`, text: line.trim() });
      }
    });

    // properties set inside @keyframes blocks
    const keyframes = /@keyframes\s+([\w-]+)\s*\{/g;
    for (let k = keyframes.exec(text); k; k = keyframes.exec(text)) {
      let depth = 1;
      let i = k.index + k[0].length;
      const start = i;
      while (depth > 0 && i < text.length) {
        if (text[i] === '{') depth++;
        else if (text[i] === '}') depth--;
        i++;
      }
      const body = text.slice(start, i);
      for (const decl of body.matchAll(/([\w-]+)\s*:/g)) {
        if (HEAVY_IN_KEYFRAMES.test(decl[1])) {
          const line = text.slice(0, start + decl.index).split('\n').length;
          found.push({ rel, line, found: `@keyframes ${k[1]} { ${decl[1]} }`, text: lines[line - 1]?.trim() ?? '' });
        }
      }
    }
  }
  return found;
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
